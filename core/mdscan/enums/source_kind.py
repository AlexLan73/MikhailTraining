"""Вид цели сканирования: что именно передали первым аргументом CLI.

Значения совпадают со строками конфига `source.kind`, поэтому вид, указанный
человеком явно, не требует отдельной таблицы перевода. Слова `yaml` здесь нет:
это ветка CLI (взять цели из файла), а не вид источника.
"""

from __future__ import annotations

from enum import Enum


class SourceKind(Enum):
    """Вид одной цели — по нему `SourceFactory` создаёт источник репозиториев."""

    LOCAL = "local"              # локальный каталог
    REMOTE_REPO = "remote_repo"  # URL одного репозитория (клонируется)
    GITHUB_ORG = "github_org"    # URL организации GitHub (раскрывается в список репозиториев)
