"""Резолв путей с кэшем каталогов — один вызов ОС на каталог, а не на файл (H-05, G-D)."""

from __future__ import annotations

from pathlib import Path


class ResolvedPathCache:
    """`resolve()` каждого файла — обращение к ОС; кэшируем его по каталогу.

    Зачем: `Path.resolve()` на Windows идёт в `nt._getfinalpathname` (~100 мкс на путь).
    Стадия 1 резолвит каждый найденный файл, а реестр (`ProcessedRegistry`) — ещё и повторно,
    вместе с корнем репозитория: на 500 файлах это 1500 обращений к ОС ≈ 0.15 с (замер H-04).

    Почему хватает каталога: псевдонимы одного и того же файла, от которых защищается обход
    (D6.2/D6.4), возникают **на уровне каталогов** — симлинк на уже просмотренную папку, второй
    worktree того же репозитория, репозиторий в списке дважды. Имя файла внутри каталога
    уникально, поэтому резолвим каталог и подставляем имя как есть: 500 файлов в 96 каталогах —
    96 обращений к ОС вместо 500 (замер H-05: 0.061 → 0.015 с).

    Потокобезопасен без блокировки: единственная запись — `dict.setdefault` (атомарна под GIL),
    а результат для одного ключа не зависит от того, какой поток обхода его посчитал.
    """

    def __init__(self) -> None:
        self._directories: dict[Path, Path] = {}

    def file(self, path: Path) -> Path:
        """Абсолютный путь файла: резолв его каталога (из кэша) + имя файла как есть."""
        return self.directory(path.parent) / path.name

    def directory(self, path: Path) -> Path:
        """Абсолютный путь каталога; повторный вызов берёт готовый результат из кэша."""
        cached = self._directories.get(path)
        if cached is not None:
            return cached
        return self._directories.setdefault(path, path.resolve())
