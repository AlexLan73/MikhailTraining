"""Сентинелы конца стадий конвейера: конец обхода и конец результатов.

Почему отдельный тип, а не `None`/`0`/`""` (D3): «пустое» значение может оказаться
настоящими данными, и потребитель молча выйдет из цикла — это тихая потеря данных,
худший класс ошибок конвейера. Уникальный объект сравнивается по `is` и совпасть
с полезной нагрузкой не может.

Сентинела **два**, а не один общий: у стадий разные моменты остановки (D3.1), а при
отладке по имени в логе сразу видно, чей конец пришёл.
"""

from __future__ import annotations

from typing import Final


class _Sentinel:
    """Маркер конца очереди. Приватный: экземпляры создаются только здесь.

    Своих экземпляров никто больше не заводит — иначе появится «второй END_RESULTS»,
    который не пройдёт сравнение `item is sentinel`.
    """

    __slots__ = ("_name",)

    def __init__(self, name: str) -> None:
        self._name = name

    @property
    def name(self) -> str:
        """Имя маркера — идёт в лог и в сообщения об ошибках."""
        return self._name

    def __repr__(self) -> str:
        return f"<sentinel {self._name}>"


#: Конец стадии 1 (обход): кладётся в `TaskQueue` по одному на каждый parse-worker (D3.1).
END_DISCOVERY: Final = _Sentinel("END_DISCOVERY")

#: Конец стадии 2 (разбор): кладётся в `ResultQueue` один раз, после `TaskQueue.join()`.
END_RESULTS: Final = _Sentinel("END_RESULTS")
