"""Все исключения пакета `core.mdscan` в одном файле.

Почему один файл, а не «класс = файл» (правило 09 п.2): исключения — такой же
плоский словарь типов, как `Enum`; разбросанные по модулям, они порождают
циклические импорты и «свои» иерархии в каждом таске. Иерархия здесь одна:
любое исключение пакета ловится как `MdScanError`.
"""

from __future__ import annotations


class MdScanError(Exception):
    """Базовое исключение пакета: ловится одним `except` в точке входа."""


class ConfigError(MdScanError):
    """Ошибка конфигурации (некорректный yaml, невалидное значение) — код возврата 2."""


class UnknownFieldError(ConfigError):
    """Переопределение `-поле:значение` с неизвестным полем.

    В тексте сообщения ожидается подсказка «похожие поля: …», чтобы человек
    исправил опечатку, не читая всю конфигурацию.
    """


class MarkdownReadError(MdScanError):
    """Файл `.md` не читается (нет доступа, битая кодировка).

    Ловится воркером и превращается в `MdFileResult.error` — прогон продолжается.
    """


class GitUnavailableError(MdScanError):
    """В системе нет бинарника `git` — работать с репозиториями нечем (код возврата 3)."""


class GitHubDiscoveryError(MdScanError):
    """`gh`/REST API не смогли раскрыть организацию.

    Для ответа 429 в тексте ожидается время сброса лимита.
    """
